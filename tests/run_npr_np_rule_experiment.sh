#!/usr/bin/env bash
# Compare the accepted Kadiweu TBP parser rules (A) with the experimental
# NPR-wrapping rules (B) on the fixed 36-sentence expanded test suite.

set -uo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
REPO_ROOT=$(cd -- "$SCRIPT_DIR/.." && pwd)

# Override any of these paths by exporting the corresponding variable.
PARSER_DIR=${PARSER_DIR:-"$HOME/Dropbox/projects/2025/post-doc/parser"}
ACCEPTED_RULES=${ACCEPTED_RULES:-"$PARSER_DIR/kadiweu_parser_300726.pdt.txt"}
CANDIDATE_RULES=${CANDIDATE_RULES:-"$PARSER_DIR/kadiweu_parser_300726.pdt.npr-np-test.txt"}
DEFINITIONS=${DEFINITIONS:-"$PARSER_DIR/kadiweu_parser_definitions_050726.txt"}
CORPUSSEARCH=${CORPUSSEARCH:-corpussearch}
PYTHON=${PYTHON:-python3}

RUNNER=${RUNNER:-"$REPO_ROOT/src/run_kadiweu_parser_rules.py"}
ARTIFACT_DIR=${ARTIFACT_DIR:-"$REPO_ROOT/data/generated/constituency"}
INPUT=${INPUT:-"$ARTIFACT_DIR/kadiweu-parser-expanded-test.pos"}
REFERENCE=${REFERENCE:-"$ARTIFACT_DIR/kadiweu-parser-expanded-test.gold.psd"}
EXPERIMENT=${EXPERIMENT:-npr-np-test}

A_PREFIX="$ARTIFACT_DIR/kadiweu-parser-expanded-test-A"
B_PREFIX="$ARTIFACT_DIR/kadiweu-parser-expanded-test-B-$EXPERIMENT"
SUFFIX="skip-77-122"
TRANSITION_REPORT="$ARTIFACT_DIR/kadiweu-parser-expanded-test-A-to-B-$EXPERIMENT.tsv"
HASH_MANIFEST="$ARTIFACT_DIR/kadiweu-parser-expanded-test-$EXPERIMENT-hashes.txt"

usage() {
    cat <<'EOF'
Usage: tests/run_npr_np_rule_experiment.sh

Runs accepted rules A and candidate rules B on the same fixed input, then
writes the A-to-B transition report. Configuration is through environment
variables; commonly useful overrides are:

  PARSER_DIR       directory containing restricted TBP files
  ACCEPTED_RULES   accepted compatible rule file (A)
  CANDIDATE_RULES  experimental rule file (B)
  DEFINITIONS      TBP definitions file
  CORPUSSEARCH     CorpusSearch executable or command
  ARTIFACT_DIR     input/reference and output directory
  EXPERIMENT       label used in candidate artifact names

Exit status 1 means structural differences were reported, not that execution
failed. Exit status 2 indicates an execution or configuration error.
EOF
}

if [[ ${1:-} == --help || ${1:-} == -h ]]; then
    usage
    exit 0
fi
if (($# != 0)); then
    usage >&2
    exit 2
fi

require_file() {
    local path=$1
    if [[ ! -f $path ]]; then
        printf 'error: required file not found: %s\n' "$path" >&2
        exit 2
    fi
}

require_command() {
    local command_name=$1
    if ! command -v "$command_name" >/dev/null 2>&1; then
        printf 'error: required command not found: %s\n' "$command_name" >&2
        exit 2
    fi
}

require_file "$RUNNER"
require_file "$ACCEPTED_RULES"
require_file "$CANDIDATE_RULES"
require_file "$DEFINITIONS"
require_file "$INPUT"
require_file "$REFERENCE"
require_command "$PYTHON"
require_command sha256sum

mkdir -p "$ARTIFACT_DIR"

# A comparison result of 1 is meaningful output: the runner found structural
# differences. Only status 2 (or another unexpected status) aborts the cycle.
run_parser() {
    local label=$1
    shift

    printf '\nRunning %s...\n' "$label"
    "$PYTHON" "$RUNNER" "$@"
    local status=$?

    case $status in
        0)
            printf '%s: no structural differences against the reference.\n' "$label"
            ;;
        1)
            printf '%s: structural differences reported; continuing the experiment.\n' "$label" >&2
            ;;
        *)
            printf 'error: %s failed with exit status %d.\n' "$label" "$status" >&2
            exit 2
            ;;
    esac
    return "$status"
}

run_parser "accepted run A" \
    "$ACCEPTED_RULES" \
    "$INPUT" \
    --definitions "$DEFINITIONS" \
    --skip-rule 77 \
    --skip-rule 122 \
    --corpussearch "$CORPUSSEARCH" \
    --output "$A_PREFIX.psd" \
    --expected "$REFERENCE" \
    --comparison-report "$A_PREFIX-comparison.tsv" \
    --diff "$A_PREFIX.diff" \
    --work-dir "${A_PREFIX}-run-${SUFFIX}" \
    --keep-intermediate \
    --log "$A_PREFIX-run.tsv"
a_status=$?

run_parser "candidate run B ($EXPERIMENT)" \
    "$CANDIDATE_RULES" \
    "$INPUT" \
    --definitions "$DEFINITIONS" \
    --skip-rule 77 \
    --skip-rule 122 \
    --corpussearch "$CORPUSSEARCH" \
    --output "$B_PREFIX.psd" \
    --expected "$REFERENCE" \
    --accepted-output "$A_PREFIX.psd" \
    --comparison-report "$B_PREFIX-comparison.tsv" \
    --transition-report "$TRANSITION_REPORT" \
    --diff "$B_PREFIX.diff" \
    --work-dir "${B_PREFIX}-run-${SUFFIX}" \
    --keep-intermediate \
    --log "$B_PREFIX-run.tsv"
b_status=$?

{
    printf '# SHA-256 inputs for experiment %s\n' "$EXPERIMENT"
    printf '# Generated by tests/run_npr_np_rule_experiment.sh\n'
    sha256sum "$ACCEPTED_RULES" "$CANDIDATE_RULES" "$DEFINITIONS" "$INPUT" "$REFERENCE"
} >"$HASH_MANIFEST"

printf '\nExperiment complete.\n'
printf 'A output:          %s\n' "$A_PREFIX.psd"
printf 'B output:          %s\n' "$B_PREFIX.psd"
printf 'A-to-B changes:    %s\n' "$TRANSITION_REPORT"
printf 'Input hashes:      %s\n' "$HASH_MANIFEST"

# Preserve the runner's comparison semantics for callers and CI: return 1 if
# either run contains structural differences, otherwise return 0.
if ((a_status == 1 || b_status == 1)); then
    exit 1
fi
exit 0
